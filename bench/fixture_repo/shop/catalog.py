def find_by_sku(sku):
    """Return (name, category, price, stock) for a SKU.

    SKUs are case-insensitive and may carry surrounding whitespace.
    """
    try:
        return PRODUCTS[sku]
    except KeyError:
        raise UnknownProduct(sku) from None


def price_of(sku):
    return find_by_sku(sku)[2]


def in_category(category):
    """SKUs in a category, sorted."""
    return sorted(sku for sku, row in PRODUCTS.items() if row[1] == category)


def categories():
    return sorted({row[1] for row in PRODUCTS.values()})
